#!/usr/bin/env bash
# Push a pack-tree.sh tree and a make-node.sh node to the device and write the device-side launcher.
#
# Usage: deploy.sh <tree> <node-out> <host-alias>
#   <tree>        pack-tree.sh <out>/tree
#   <node-out>    make-node.sh <out> (uses <node-out>/bin/node)
#   <host-alias>  ssh alias of the device terminal sandbox (e.g. hmos)
#
# Device layout (DSH_OH_ROOT, default /data/storage/el2/base/dsh — the only directory where write, exec, dlopen,
# UDS and 0600 all hold):
#   tree/            package.json + flat node_modules + oh/ (SHA256SUMS, elf-sweep.txt, device-smoke.cjs)
#   node/bin/node    self-signed node
#   bin/oh-env.sh    environment for every device-side run (sourced); loads $BASE/.env.private (push-env.sh)
#   bin/dsh-web      zsh shorthand: serve the web profile and open it in the device browser (dsh-web.zsh)
#   bin/dsh          zsh launcher: <root>/bin/dsh --profile <name> <args>; always prepends
#                    --patch tree/oh/openharmony.patch.yml (bash tool runs /usr/bin/zsh), so launcher flags such as
#                    --profile must be spelled out rather than abbreviated as `dsh <name>`
# The tree is unpacked next to the old one and swapped in with mv; the old tree is then removed.
#
# Second root: a DSH_OH_ROOT other than the default is a self-contained install for another owner (e.g. the
# Super-agent's verification root /data/storage/el2/base/dsh-sa). Its tmp, home, agents and Web documents live under the
# root (bin/root.patch.yml sets the documents directory); bin/oh-env.sh loads <root>/env (push-env.sh --root) instead
# of $BASE/.env.private, and oh's env.sh only when that file sets DSH_OH_WITH_OH=1; ~/.zshrc is never edited; only
# processes under the root block the deploy. DSH_OH_OWNER (default "maintainer") must match <root>/.owner, which the
# first deploy of a second root writes; the default root belongs to the maintainer. The default root deploys as before.
. "$(dirname "$0")/lib.sh"
[ $# -eq 3 ] || die "usage: deploy.sh <tree> <node-out> <host-alias>"
TREE=$(cd "$1" && pwd); NODE=$(cd "$2" && pwd)/bin/node; HOST=$3
ROOT="${DSH_OH_ROOT:-$OH_DEFAULT_ROOT}"
BASE=$OH_BASE
OWNER="${DSH_OH_OWNER:-maintainer}"
[ -f "$TREE/node_modules/@deepseek-ai/dsh/lib/bin.js" ] && [ -f "$TREE/oh/openharmony.patch.yml" ] || die "$TREE is not a pack-tree.sh tree"
[ -x "$NODE" ] && has_section "$NODE" .codesign && has_section "$NODE" .permission || die "$NODE is not a make-node.sh node"
case $ROOT in "$BASE"/*) ;; *) die "DSH_OH_ROOT must be under $BASE" ;; esac

if [ "$ROOT" = "$OH_DEFAULT_ROOT" ]; then
  [ "$OWNER" = maintainer ] || die "$ROOT is the maintainer's root; DSH_OH_OWNER=$OWNER deploys to its own DSH_OH_ROOT"
  log "device check ($HOST)"
  "$OH_SSH" "$HOST" 'ps -ef' | grep -E 'hvigor|dsh/node/bin/node|lib/bin.js' | grep -v grep && die "a hvigor or dsh process is running on the device; retry later"
else
  oh_second_root "$ROOT"
  log "device check ($HOST, processes under $ROOT)"
  ps=$("$OH_SSH" "$HOST" 'ps -ef')
  printf '%s\n' "$ps" | grep -F "$ROOT/" | grep -v grep && die "a process from $ROOT is running on the device; retry later"
  others=$(printf '%s\n' "$ps" | grep -E 'hvigor|/node/bin/node|lib/bin.js' | grep -vF "$ROOT/" | grep -vc grep || true)
  [ "$others" = 0 ] || log "note: $others hvigor/dsh process(es) of other roots run on the device; they do not block $ROOT"
  oh_owner "$HOST" "$ROOT" "$OWNER" claim
fi

log "push node + tree to $HOST:$ROOT"
"$OH_SSH" "$HOST" "mkdir -p '$ROOT/node/bin' '$ROOT/bin' && rm -rf '$ROOT/tree.new' '$ROOT/tree.old' && mkdir '$ROOT/tree.new'"
cat "$NODE" | "$OH_SSH" "$HOST" "cat > '$ROOT/node/bin/node.new' && chmod 755 '$ROOT/node/bin/node.new' && mv '$ROOT/node/bin/node.new' '$ROOT/node/bin/node'"
tar -C "$TREE" -cf - . | "$OH_SSH" "$HOST" "tar -xf - -C '$ROOT/tree.new'"
"$OH_SSH" "$HOST" "cd '$ROOT' && { [ ! -d tree ] || mv tree tree.old; } && mv tree.new tree && rm -rf tree.old"

log "write launcher"
if [ "$ROOT" = "$OH_DEFAULT_ROOT" ]; then
"$OH_SSH" "$HOST" "cat > '$ROOT/bin/oh-env.sh'" <<EOF
# Generated by scripts/openharmony/deploy.sh. POSIX sh; sourced by bin/dsh and smoke runs.
DSH_OH_ROOT='$ROOT'
# /tmp is writable but cannot exec, dlopen or bind a UNIX socket on the device.
TMPDIR='$BASE/tmp'
# node-addon-native-custom-loader copies .node files into tmpdir before loading; load in place instead.
NARB_DISABLE_NATIVE_CACHE=1
# No bash and no passwd entry in the terminal sandbox; os.userInfo() fails without SHELL. HiShell logs in with zsh.
SHELL=/usr/bin/zsh
# Home directories cannot hold hard links and read back 0600 as 0640; keep dsh state under el2 base.
# Defaults only: a caller may point a run at another home under el2 base (smoke.sh --m3 does).
DSH_HOME="\${DSH_HOME:-$BASE/dsh-home}"
DSH_AGENTS_HOME="\${DSH_AGENTS_HOME:-$BASE/dsh-agents}"
export DSH_OH_ROOT TMPDIR NARB_DISABLE_NATIVE_CACHE SHELL DSH_HOME DSH_AGENTS_HOME
mkdir -p "\$TMPDIR" "\$DSH_HOME" "\$DSH_AGENTS_HOME"
# Keys follow the host convention: one ~/.env.private, copied here by push-env.sh (home reads 0600 back as 0640).
if [ -r '$BASE/.env.private' ]; then set -a; . '$BASE/.env.private'; set +a; fi
# oh on the device (oh-cli scripts/install-hmos.sh): puts oh, the CLT node / hvigor / hdc and OH_CONFIG_DIR in reach of
# the bash tool however dsh was launched; its skills go to \$DSH_HOME/skills (oh skills install --agent dsh).
if [ -r "\$HOME/.config/oh/env.sh" ]; then . "\$HOME/.config/oh/env.sh"; fi
# The copied file points proxies at the VM's mihomo (127.0.0.1:7897), which does not exist on the device;
# the device reaches the network directly.
unset HTTP_PROXY HTTPS_PROXY http_proxy https_proxy ALL_PROXY all_proxy NO_PROXY no_proxy
EOF
"$OH_SSH" "$HOST" "cat > '$ROOT/bin/dsh' && chmod 755 '$ROOT/bin/dsh'" <<EOF
#!/usr/bin/zsh
# Generated by scripts/openharmony/deploy.sh: run dsh from the deployed tree under the self-signed node.
. '$ROOT/bin/oh-env.sh'
exec '$ROOT/node/bin/node' '$ROOT/tree/node_modules/@deepseek-ai/dsh/lib/bin.js' --patch '$ROOT/tree/oh/openharmony.patch.yml' "\$@"
EOF
else
"$OH_SSH" "$HOST" "mkdir -p '$ROOT/tmp' '$ROOT/home' '$ROOT/agents' '$ROOT/documents' && cat > '$ROOT/bin/oh-env.sh'" <<EOF
# Generated by scripts/openharmony/deploy.sh for a second root (owner $OWNER). POSIX sh; sourced by bin/dsh and smoke
# runs. Everything a run writes stays under the root; keys come only from $ROOT/env (push-env.sh --root), never
# from $BASE/.env.private.
DSH_OH_ROOT='$ROOT'
# /tmp is writable but cannot exec, dlopen or bind a UNIX socket on the device.
TMPDIR='$ROOT/tmp'
# node-addon-native-custom-loader copies .node files into tmpdir before loading; load in place instead.
NARB_DISABLE_NATIVE_CACHE=1
# No bash and no passwd entry in the terminal sandbox; os.userInfo() fails without SHELL. HiShell logs in with zsh.
SHELL=/usr/bin/zsh
# An inherited home is honoured only inside this root (smoke.sh points runs at homes under $ROOT/tmp); any other,
# such as the DSH_HOME that HiShell's ~/.zshrc exports for the maintainer's root, is replaced.
case "\${DSH_HOME:-}" in *..*) DSH_HOME='$ROOT/home' ;; '$ROOT'/*) ;; *) DSH_HOME='$ROOT/home' ;; esac
case "\${DSH_AGENTS_HOME:-}" in *..*) DSH_AGENTS_HOME='$ROOT/agents' ;; '$ROOT'/*) ;; *) DSH_AGENTS_HOME='$ROOT/agents' ;; esac
export DSH_OH_ROOT TMPDIR NARB_DISABLE_NATIVE_CACHE SHELL DSH_HOME DSH_AGENTS_HOME
mkdir -p "\$TMPDIR" "\$DSH_HOME" "\$DSH_AGENTS_HOME"
# The root's own env file (NAME=value lines). Only that file can opt into oh's environment (OH_CONFIG_DIR, hdc, oh
# credentials) with DSH_OH_WITH_OH=1.
DSH_OH_WITH_OH=0
if [ -r '$ROOT/env' ]; then set -a; . '$ROOT/env'; set +a; fi
if [ "\$DSH_OH_WITH_OH" = 1 ] && [ -r "\$HOME/.config/oh/env.sh" ]; then . "\$HOME/.config/oh/env.sh"; fi
# The device reaches the network directly; the M runs need none.
unset HTTP_PROXY HTTPS_PROXY http_proxy https_proxy ALL_PROXY all_proxy NO_PROXY no_proxy
EOF
"$OH_SSH" "$HOST" "cat > '$ROOT/bin/root.patch.yml'" <<EOF
# Generated by scripts/openharmony/deploy.sh: this root's Web workspaces live under the root. bin/dsh applies this file
# after tree/oh/openharmony.patch.yml, whose documentsDirectory is the maintainer's.
- id: workspace-controller
  config:
    documentsDirectory: $ROOT/documents
EOF
"$OH_SSH" "$HOST" "cat > '$ROOT/bin/dsh' && chmod 755 '$ROOT/bin/dsh'" <<EOF
#!/usr/bin/zsh
# Generated by scripts/openharmony/deploy.sh: run dsh from the deployed tree under the self-signed node (second root).
. '$ROOT/bin/oh-env.sh'
exec '$ROOT/node/bin/node' '$ROOT/tree/node_modules/@deepseek-ai/dsh/lib/bin.js' --patch '$ROOT/tree/oh/openharmony.patch.yml' --patch '$ROOT/bin/root.patch.yml' "\$@"
EOF
fi

if [ "$ROOT" = "$OH_DEFAULT_ROOT" ]; then
  log "install dsh-web and put $ROOT/bin on the HiShell PATH (~/.zshrc block, idempotent)"
  "$OH_SSH" "$HOST" "cat > '$ROOT/bin/dsh-web' && chmod 755 '$ROOT/bin/dsh-web'" <"$(dirname "$0")/dsh-web.zsh"
  # The block is matched by its marker and then by this root's PATH line: a block that names another root is reported,
  # never taken for "already done" silently.
  "$OH_SSH" "$HOST" "if grep -q '^# >>> dsh (openharmony deploy.sh) >>>' ~/.zshrc 2>/dev/null; then grep -qF 'path=($ROOT/bin \$path)' ~/.zshrc || echo '[oh] note: the ~/.zshrc dsh block names another root; left unchanged' >&2; else printf '%s\\n' '# >>> dsh (openharmony deploy.sh) >>>' 'path=($ROOT/bin \$path)' 'export DSH_HOME=$BASE/dsh-home' '# <<< dsh <<<' >> ~/.zshrc; fi"
else
  log "install dsh-web; ~/.zshrc is left alone for a second root (run $ROOT/bin/dsh by path)"
  "$OH_SSH" "$HOST" "cat > '$ROOT/bin/dsh-web' && chmod 755 '$ROOT/bin/dsh-web'" <"$(dirname "$0")/dsh-web.zsh"
fi

log "verify on device"
"$OH_SSH" "$HOST" "cd '$ROOT/tree' && sha256sum -c oh/SHA256SUMS && sha256sum '$ROOT/node/bin/node' && du -sh '$ROOT/tree'"
sha256sum "$NODE"
log "deployed: sh $ROOT/bin/dsh --help"
